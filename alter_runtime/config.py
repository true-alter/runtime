    @classmethod
    def load(cls) -> DaemonConfig:
        """Load config from environment + YAML file + defaults.

        Raises
        ------
        ConfigError
            If any endpoint is non-``https://`` after env/YAML overrides,
            or if the YAML override is present without ``ALTER_RUNTIME_DEV=1``.
        """
        config = cls()
        # Endpoint fields pinned by an explicit ALTER_*_ENDPOINT env override.
        # The prod-default self-heal below leaves these alone so an
        # explicitly-configured endpoint is preserved as set.
        env_pinned_endpoints: set[str] = set()

        # Member-set behaviour toggles, applied BEFORE any env read so that an
        # explicit ALTER_* var still wins. Precedence stays env > file >
        # default, as the module docstring states.
        _apply_behaviour_toggles(config)

        # Environment overrides
