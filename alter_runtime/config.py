"""XDG-compliant configuration and session loading.

The alter-runtime daemon reads its configuration from three sources, in order
of precedence:

1. Environment variables (ALTER_RUNTIME_*)
2. User config file at $XDG_CONFIG_HOME/alter/runtime.yaml (default
   ~/.config/alter/runtime.yaml), dev-only, see the gate at ``DaemonConfig.load``
3. Behaviour toggles the member set from their own CLI, at
   $XDG_CONFIG_HOME/alter/daemon-toggles.json. Booleans on a closed allowlist
   and nothing else, which is why it needs no dev gate.
4. Built-in defaults

The authoritative identity session is written by the separate CLI
into its OS-native secure credential store (DPAPI / macOS
Keychain / libsecret, with an AES-256-GCM encrypted-file
fallback at $XDG_CONFIG_HOME/alter/enc/session.bin keyed by
$XDG_CONFIG_HOME/alter/enc-keyfile). Older installs may still carry the
legacy plaintext $XDG_CONFIG_HOME/alter/session.json. We read the session
through the same store contract the CLI uses but never mutate it - the
daemon does not manage login, never writes any store backend, and never
migrates between backends (that is the CLI's job).

Socket paths:
- Linux:   /run/user/$UID/alter.sock
- macOS:   ~/Library/Application Support/alter/runtime.sock
- Windows: \\\\.\\pipe\\alter-runtime   (Named Pipe, not yet supported)
"""

