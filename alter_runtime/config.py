        _sr_flag = os.environ.get("ALTER_RUNTIME_SESSION_REFRESH", "").lower()
        if _sr_flag in ("0", "false", "no", "off"):
            config.session_refresh_enabled = False
        elif _sr_flag in ("1", "true", "yes", "on"):
            config.session_refresh_enabled = True
        if sr_lead := os.environ.get("ALTER_RUNTIME_SESSION_REFRESH_LEAD_SECONDS"):
            try:
                config.session_refresh_lead_seconds = float(sr_lead)
            except ValueError:
                pass  # Ignore malformed override; default stands.
        if sr_timeout := os.environ.get("ALTER_RUNTIME_SESSION_REFRESH_SUBPROCESS_TIMEOUT_SECONDS"):
            try:
                config.session_refresh_subprocess_timeout_seconds = float(sr_timeout)
            except ValueError:
                pass  # Ignore malformed override; default stands.

