    #: subscriber refuses to construct otherwise (see the startup guard)
    #: to prevent self-certifying-frame attacks where a frame's
    #: declared pubkey is trusted solely on its own authority.
    #:
    #: Override via ``ALTER_RUNTIME_FRAME_SIG_PUBKEY``.
