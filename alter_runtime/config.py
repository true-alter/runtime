@dataclass(frozen=True)
class Session:
    """Snapshot of the CLI session.json file.

    Mirrors the shape the CLI writes on login.
    """

    handle: str
    api: str
    jwt: str
    jwt_expires_at: str
    consent_tier: int
    user_id: str
    email: str
    orgs: list[dict[str, Any]] = field(default_factory=list)
    id_token: str | None = None
    refresh_token: str | None = None
    refresh_expires_at: str | None = None
    logged_in_at: str | None = None
    #: Per-invocation ES256 signing key id. Written by ``alter login`` and
    #: cached here alongside the private half written to
    #: ``~/.config/alter/signing-keys/<kid>.pem`` (or the legacy
    #: ``signing-key.pem``). When present, the daemon builds a compact JWS
    #: ``Mcp-Invocation-Signature`` header for every MCP ``tools/call`` so
    #: the backend's per-invocation signing gate passes.
    signing_kid: str | None = None
    #: SHA-256 (base64url) of the DER-encoded SubjectPublicKeyInfo (SPKI) of
    #: the ES256 signing key. Written by ``alter login`` alongside
    #: ``signing_kid`` (current login format). The daemon uses this to detect a
    #: split-brain where the resolved private key no longer matches what the
    #: session recorded at login time, refusing to sign with the wrong key
    #: rather than emitting a JWS the server will reject as
    #: ``handle_mismatch``.  ``None`` on legacy sessions (legacy fallback:
    #: attempt to sign and let the server surface any mismatch).
    signing_key_fingerprint: str | None = None
    #: Long-lived member API key written by ``alter login``. This is the
    #: credential the bridge sends as ``X-ALTER-API-Key`` for member-self tools
    #: (doctrine, messaging, alignment, consent, attunement) - those tools
    #: require ``member_self`` scope, which the 24h bearer JWT does NOT carry.
    #: The doctrine-projection poller authenticates with this key; ``None`` when
    #: the session predates the member-key cutover (the poller then soft-fails
    #: the doctrine read and logs, never crashes).
    member_api_key: str | None = None
    #: The member's UUID (assessment-DB ``members.id``). Carried for parity with
    #: the bridge; the backend resolves ownership from the validated credential,
    #: not from this value. ``None`` on legacy sessions.
    member_id: str | None = None


class SessionRef:
    """Mutable holder for the live :class:`Session`.

    Subscribers that need a fresh JWT after a proactive refresh read
    ``.current.jwt`` through this holder instead of holding a frozen
    :class:`Session` snapshot.  When the :class:`SessionRefresher` rotates the
    token on disk it calls :meth:`set` once; every subsequent ``.current``
    read gets the updated JWT with zero additional coupling between
    components.

    Thread safety
    -------------
    No lock is needed.  The daemon runs a single-threaded asyncio event loop
    where coroutine scheduling is cooperative, so all reads and the single
    write are serialised by the loop (same justification as
    ``DaemonCapCache``'s plain-dict stores).
    """

    __slots__ = ("_session",)

    def __init__(self, session: Session) -> None:
        self._session: Session = session

    @property
    def current(self) -> Session:
        """Return the most-recently loaded :class:`Session`."""
        return self._session

    def set(self, session: Session) -> None:
        """Replace the held session (called by :class:`SessionRefresher`)."""
        self._session = session

    def reload(self) -> Session | None:
        """Re-read the session from disk and update the holder if valid.

        Returns the new :class:`Session` on success, ``None`` if
        :func:`load_session` returns nothing (e.g. the file disappeared).
        The holder is only updated on a valid reload.
        """
        fresh = load_session()
        if fresh is not None:
            self._session = fresh
        return fresh


def session_path() -> Path:
    """Path to the CLI's legacy plaintext session.json.

    Kept for the legacy-fallback read and the ``ALTER_SESSION_FILE``
    override. The CLI's encrypted-session cutover deletes this file after
    migrating the session into the secure store - see
    :func:`load_session` for the full resolution order.
    """
    override = os.environ.get("ALTER_SESSION_FILE")
    if override:
        return Path(override).expanduser()
    return config_dir() / "session.json"


def enc_session_path() -> Path:
    """Path to the CLI's encrypted-file-backend session blob.

    Written by the CLI's secure store when no
    OS-native credential tool is available (or when
    ``ALTER_SECURE_STORE_BACKEND=file`` forces the file backend). Blob
    layout: ``[12-byte IV][16-byte GCM tag][AES-256-GCM ciphertext]``.
    """
    return config_dir() / "enc" / "session.bin"


def enc_keyfile_path() -> Path:
    """Path to the 32-byte raw AES-256 key for the encrypted-file backend.

    Mirrors the CLI's active-keyfile resolution. The key and the
    ciphertext are separate files so reading either in isolation yields
    nothing; there is no device binding (documented CLI trade-off).
    """
    return config_dir() / "enc-keyfile"


# ---------------------------------------------------------------------------
# Secure-store read surface (read-only mirror of the CLI's contract)
# ---------------------------------------------------------------------------
#
# The CLI's secure store selects ONE
# backend at runtime: DPAPI (win32), macOS Keychain (darwin), libsecret
# (linux), or the AES-256-GCM encrypted-file fallback. The daemon cannot
# safely replicate the CLI's *probe-then-pick* selection - a systemd user
# service probes a different environment than the interactive shell that ran
# ``alter login`` (e.g. D-Bus session bus present in one, absent in the
# other). Instead the daemon tries each read surface in a deterministic
# order and accepts the first VALID session; the surfaces are mutually
# exclusive in practice (the CLI writes to exactly one), so first-hit-wins
# is unambiguous.
#
# Every read here is strictly read-only: no writes, no migration, no
# deletion. The OS-tool invocations are the same stable public CLI
# contracts (`secret-tool lookup`, `security find-generic-password`) that
# the CLI itself shells out to - the one place the daemon must implement
# crypto itself is the encrypted-file fallback, whose 3-field blob layout
# is the CLI's documented on-disk format (and which `cryptography`, already
# a base dependency for Ed25519 frame verification, decrypts natively).

#: Service / account keys used by the CLI's secure store. Must match
#: the CLI's secure-store service and session-store account names.
SECURE_STORE_SERVICE: str = "alter-cli"
SECURE_STORE_SESSION_ACCOUNT: str = "session"
SECURE_STORE_SIGNING_KEY_ACCOUNT: str = "signing-key"

#: Timeout for OS credential-tool shell-outs. Matches the CLI's own 10s
#: execFileSync budget - a locked keyring / frozen D-Bus must not wedge
#: daemon startup.
_OS_STORE_TIMEOUT_SECONDS: float = 10.0


def read_os_secret_store(account: str = SECURE_STORE_SESSION_ACCOUNT) -> str | None:
    """Read a named account from the platform's native credential store.

    Returns the raw secret string, or ``None`` when the tool is absent,
    the item is missing, the call times out, or the platform has no
    supported native read (win32 - the daemon's Windows surface is not yet
    supported; DPAPI read is deferred. The enc-file and legacy fallbacks
    still apply there). Never raises.

    Parameters
    ----------
    account:
        The account name within the ``alter-cli`` service namespace.
        Defaults to ``"session"``; pass ``"signing-key"`` to read the
        ES256 private-key envelope written by ``alter login`` (current
        login format, a JSON envelope ``{v,kid,private_key_pem,
        public_key_fingerprint}``; legacy stores a bare PKCS8 PEM).
    """
    try:
        if sys.platform.startswith("linux"):
            # Mirror the CLI's libsecret probe: without a session D-Bus the
            # lookup would hit the system bus or hang - skip outright.
            if not os.environ.get("DBUS_SESSION_BUS_ADDRESS"):
                return None
            if shutil.which("secret-tool") is None:
                return None
            result = subprocess.run(
                [
                    "secret-tool",
                    "lookup",
                    "service",
                    SECURE_STORE_SERVICE,
                    "account",
                    account,
                ],
                capture_output=True,
                text=True,
                timeout=_OS_STORE_TIMEOUT_SECONDS,
                check=False,
            )
            if result.returncode != 0 or not result.stdout:
                return None
            return result.stdout
        if sys.platform == "darwin":
            if not Path("/usr/bin/security").exists():
                return None
            result = subprocess.run(
                [
                    "/usr/bin/security",
                    "find-generic-password",
                    "-s",
                    SECURE_STORE_SERVICE,
                    "-a",
                    account,
                    "-w",
                ],
                capture_output=True,
                text=True,
                timeout=_OS_STORE_TIMEOUT_SECONDS,
                check=False,
            )
            if result.returncode != 0 or not result.stdout:
                return None
            return result.stdout
    except (OSError, subprocess.TimeoutExpired, subprocess.SubprocessError):
        return None
    return None


def _read_os_secret_store() -> str | None:
    """Read the session blob from the platform's native credential store.

    Thin wrapper over :func:`read_os_secret_store` that preserves the
    pre-generalisation call signature used by :func:`load_session`.
    """
    return read_os_secret_store(SECURE_STORE_SESSION_ACCOUNT)


def read_enc_store(enc_filename: str = "session.bin") -> str | None:
    """Decrypt a named blob from the CLI's encrypted-file backend.

    Format per the CLI's encrypted-file backend:
    ``enc/<enc_filename>`` = ``[12-byte IV][16-byte auth tag][ciphertext]``,
    AES-256-GCM with the 32-byte raw key at ``enc-keyfile``. Returns the
    decrypted UTF-8 string or ``None`` on any failure (missing files,
    truncated blob, wrong-size key, bad tag). Never raises.

    Parameters
    ----------
    enc_filename:
        Filename (NOT a path) within ``~/.config/alter/enc/``. Defaults
        to ``"session.bin"`` (the session blob). Pass ``"signing-key.bin"``
        to read the ES256 private-key envelope (same blob layout, same
        keyfile).
    """
    try:
        blob = (config_dir() / "enc" / enc_filename).read_bytes()
        key = enc_keyfile_path().read_bytes()
    except OSError:
        return None
    if len(blob) < 28 or len(key) != 32:
        # 12-byte IV + 16-byte tag minimum; key must be exactly AES-256.
        return None
    # Imported lazily to keep module import cheap; `cryptography` is already
    # a base dependency (Ed25519 frame-signature verification).
    from cryptography.hazmat.primitives.ciphers.aead import AESGCM

    iv = blob[:12]
    tag = blob[12:28]
    ciphertext = blob[28:]
    try:
        # AESGCM.decrypt expects ciphertext||tag; the CLI stores the tag
        # BEFORE the ciphertext, so reorder here.
        plaintext = AESGCM(key).decrypt(iv, ciphertext + tag, None)
    except Exception:
        # InvalidTag / malformed input - corrupt blob or rotated keyfile.
        return None
    try:
        return plaintext.decode("utf-8")
    except UnicodeDecodeError:
        return None


def _read_enc_store() -> str | None:
    """Decrypt the CLI's encrypted-file-backend session blob.

    Thin wrapper over :func:`read_enc_store` that preserves the
    pre-generalisation call signature used by :func:`load_session`.
    """
    return read_enc_store("session.bin")


def _parse_consent_tier(value: Any) -> int:
    """Normalise ``consent_tier`` to the integer ~alter uses internally.

    The CLI writes the consent tier as a string label
    (``"L1"``, ``"L2"``, ``"L3"``, ``"L4"``) - see the SDK type
    definitions and the canonical session.json
    written by ``alter login``. The Python runtime stores it as the numeric
    tier. Accept both shapes plus the fallback default so a hand-edited
    session file cannot brick the daemon.
    """
    if isinstance(value, bool):
        # bool is a subclass of int - reject it explicitly to avoid
        # True → 1 sneak-through from a typo in session.json.
        return 1
    if isinstance(value, int):
        if 1 <= value <= 4:
            return value
        return 1
    if isinstance(value, str):
        stripped = value.strip()
        if not stripped:
            return 1
        # "L1".."L4" → 1..4
        if len(stripped) == 2 and stripped[0] in ("L", "l") and stripped[1].isdigit():
            tier = int(stripped[1])
            if 1 <= tier <= 4:
                return tier
        # Raw numeric strings "1".."4" as a last resort.
        try:
            tier = int(stripped)
        except ValueError:
            return 1
        if 1 <= tier <= 4:
            return tier
    return 1


def _parse_session_text(raw_text: str) -> Session | None:
    """Parse + validate raw session JSON from any store backend.

    Shared by every read surface (OS store, enc-file, legacy plaintext) so
    the schema validation and the https gate apply uniformly
    regardless of where the bytes came from.
    """
    try:
        raw = json.loads(raw_text)
    except (json.JSONDecodeError, ValueError):
        return None
    if not isinstance(raw, dict):
        return None
    try:
        session = Session(
            handle=raw["handle"],
            api=raw.get("api", "https://api.truealter.com"),
            jwt=raw["jwt"],
            jwt_expires_at=raw["jwt_expires_at"],
            consent_tier=_parse_consent_tier(raw.get("consent_tier", 1)),
            user_id=raw.get("user_id", ""),
            email=raw.get("email", ""),
            orgs=list(raw.get("orgs", [])),
            id_token=raw.get("id_token"),
            refresh_token=raw.get("refresh_token"),
            refresh_expires_at=raw.get("refresh_expires_at"),
            logged_in_at=raw.get("logged_in_at"),
            signing_kid=raw.get("signing_kid") or None,
            signing_key_fingerprint=raw.get("signing_key_fingerprint") or None,
            member_api_key=raw.get("member_api_key") or None,
            member_id=raw.get("member_id") or None,
        )
    except (KeyError, TypeError):
        return None
    # reject http:// api endpoints - the subscriber
    # POSTs session.jwt as a Bearer token; plaintext delivery is not acceptable.
    try:
        _require_https("session.api", session.api)
    except ConfigError:
        return None
    return session


def _load_session_file(path: Path) -> Session | None:
    """Read + parse a plaintext session JSON file. ``None`` if absent/invalid."""
    if not path.exists():
        return None
    try:
        raw_text = path.read_text()
    except OSError:
        return None
    return _parse_session_text(raw_text)


def load_session() -> Session | None:
    """Load the CLI session, returning ``None`` if absent/invalid.

    Resolution order (first VALID session wins):

    1. ``ALTER_SESSION_FILE`` env override - an explicit plaintext JSON
       path pinned by the operator or the test suite. When set, no other
       surface is probed (the override is a redirect, not a preference).
    2. The OS-native credential store, via the same read contract
       the CLI uses (``secret-tool lookup`` on Linux,
       ``security find-generic-password`` on macOS). Skipped when
       ``ALTER_SECURE_STORE_BACKEND=file`` forces the file backend -
       mirroring the CLI's own env override.
    3. The encrypted-file fallback at
       ``$XDG_CONFIG_HOME/alter/enc/session.bin`` (AES-256-GCM, keyed by
       ``enc-keyfile``) - the backend the CLI selects on hosts without a
       reachable OS keyring.
    4. The legacy plaintext ``$XDG_CONFIG_HOME/alter/session.json``
       (pre-cutover installs; the CLI deletes it after migration).

    The daemon treats an absent session as "not yet logged in" and continues
    running in degraded mode (can still ingest signals once the user runs
    `alter login`).
    """
    # 1. Explicit override - honour it exclusively, preserving the
    #    pre-cutover behaviour where a pinned-but-missing file means
    #    "no session" rather than silently falling back to ~/.config.
    override = os.environ.get("ALTER_SESSION_FILE")
    if override:
        return _load_session_file(Path(override).expanduser())

    # 2. OS-native secure store (read-only, same contract as the CLI).
    if os.environ.get("ALTER_SECURE_STORE_BACKEND") != "file":
        raw_text = _read_os_secret_store()
        if raw_text is not None:
            session = _parse_session_text(raw_text)
            if session is not None:
                return session

    # 3. Encrypted-file fallback (enc/session.bin + enc-keyfile).
    raw_text = _read_enc_store()
    if raw_text is not None:
        session = _parse_session_text(raw_text)
        if session is not None:
            return session

    # 4. Legacy plaintext session.json.
    return _load_session_file(session_path())


